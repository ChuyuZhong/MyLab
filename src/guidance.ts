export function localGuidance(question: string) {
  if (/AIHOT|AI 情报|热点|日报|资讯/i.test(question))
    return "打开「AI 情报」，点击精选资讯、全部动态、热点榜或 AI 日报，无需密钥和本机服务。资讯可按过去 24 小时或最近 7 天、分类和关键词筛选，论文可选择论文分类。默认每 30 分钟在页面可见时检查更新，也能手动检查；短时间重复点击会复用缓存。AI 解读摘要使用已有模型接口，原文入口可查看完整内容；转为待办会打开任务编辑器。";
  if (/周报/.test(question))
    return "打开「写周报」，先选择周内任一天，再勾选公众号阅读材料和这一周实际完成的 DDL。论文只有链接时，可以展开“补充理解”填写阅读笔记；在下方补充其他工作、下周计划和 idea。点击“本地整理”可生成草稿，填写个人模型 API Key 后可点击“按我的写法生成”。稿件可直接编辑、排版预览并下载 Markdown，按周保存在本浏览器。";
  if (/每周|重复|组会|提醒/.test(question))
    return "设置每周组会：在「今天」输入“每周五下午三点准备组会”，按回车即可。需要到点提醒时，打开这条待办，在“单次提醒时间”填写第一次提醒的时间；完成后，下一次待办和提醒会按周顺延。也可以在“新建待办”中指定每周的多个日期。\n\n网页运行期间才能检查提醒，重要日程建议在「日历与计划」导出到系统日历。";
  if (/GPU|显卡|算力|申请/i.test(question))
    return "先运行本机项目的 npm run bridge，把终端配对码填到「设置与数据」。再到「GPU 资源 → 连接 / 登录」填写实验室系统根地址和账号，即可查看真实分配情况。申请草稿保存在本浏览器，实际申请和释放请通过“原管理系统”完成。";
  if (/日历|导入|同步/.test(question))
    return "在「日历与计划」点击“导入日历”，选择系统日历导出的 .ics 文件。相同文件名再次导入会更新对应日程；这是一份日历副本，不会实时同步账号。点击日期可查看安排或新增当天待办。";
  if (/安排|计划|任务|待办|DDL/i.test(question))
    return "先在「今天」记下任务，再分别设置计划日期、优先级和截止时间。计划日期表示准备什么时候做；DDL 表示必须什么时候完成，改计划不会改变 DDL。\n\n需要结合个人任务生成建议时，请到「设置与数据」填写个人模型 API Key，并在助手中勾选“本次使用今天的未完成待办”。";
  return "翻译或总结需要先到「设置与数据 → 模型与翻译」填写个人 API Key。密钥仅保留在本次打开期间。\n\n点击动态的“翻译”，或公众号导读的“AI 辅助阅读”，会把已获取内容带入助手。公众号导读可粘贴链接并通过已配对的本机服务加载正文；遇到微信验证时，通过“粘贴正文”补充内容。这里只提供使用指导，尚未请求模型。";
}
